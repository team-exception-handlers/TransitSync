@pytest.mark.parametrize("headway", [False, True])
def test_policy_hold_keeps_doors_open_and_counts_final_boardings(headway):
    """Schedule and headway holds preserve boarding and delay attribution.

    Schedule control waits from 100 to 120 without lateness. Headway control
    waits from 120 to 140 after a leader's departure at 40: 40 + 100 = 140.
    Arrivals during the hold and at HoldEnd board; an arrival 0.001 s later misses.
    """
    people = {key: person(key) for key in ("during", "boundary", "late")}
    strategy = (
        HeadwayRegulationStrategy({"P": 100})
        if headway
        else ScheduleBasedHoldingStrategy()
    )
    vehicles = [vehicle()] if headway else [vehicle(current_delay=-20)]
    if headway:
        vehicles.insert(0, vehicle("leader", arrival_s=20, departure_s=40))
    due_s = 120 if headway else 100
    closes_s = due_s + 20
    # The feeder arrives after the leader leaves: only the held train is a
    # possible missed connection for these passengers.
    starts = [
        Alighting(time_s=70, passenger_id=pid, train_id="feeder", platform_id="rem")
        for pid in people
    ]
    _, events, component = simulate(
        vehicles,
        people,
        [
            *starts,
            arrival("during", closes_s - 10),
            arrival("boundary", closes_s),
            arrival("late", closes_s + 0.001),
        ],
        decision=DecisionPipeline(strategy),
    )
    assert [(e.time_s, e.applied_s) for e in select(events, Hold)] == [(due_s, 20)]
    assert [e.time_s for e in select(events, Boarding)] == [closes_s - 10, closes_s]
    # Check the follower's final record, excluding the leader's empty departure.
    departure = next(e for e in select(events, TrainDeparture) if e.train_id == "metro")
    assert (
        departure.time_s,
        departure.hold_s,
        departure.boarded_count,
        departure.onboard_load,
    ) == (closes_s, 20, 2, 2)
    # Waiting until the timetable adds no lateness; a headway extension does.
    # Neither case should relabel a hold as an external disruption.
    assert departure.disruption_delay_s == 0
    assert departure.generated_delay_s == (20 if headway else 0)
    assert [e.passenger_id for e in select(events, MissedConnection)] == ["late"]
    platform = next(p for p in component.platform_states() if p.platform_id == "P")
    assert platform.waiting_count == 1
    assert platform.last_departure_s == closes_s


def test_suspension_and_minimum_gap_preserve_open_doors():
    """Merged dispatch constraints delay closure without hiding late boardings.

    The leader is suspended until 200. Its follower reaches the platform after
    clearance and waits for the 10-second departure gap, boarding at 205.
    """
    people = {"p": person("p")}
    _, events, _ = simulate(
        [
            vehicle("leader", arrival_s=100, departure_s=100, line_id="green"),
            vehicle("follower", arrival_s=110, departure_s=110, line_id="green"),
        ],
        people,
        [arrival("p", 205)],
        end_s=220,
        suspensions=(LineSuspension("green", 100, 200),),
    )
    assert [
        (e.train_id, e.time_s, e.boarded_count) for e in select(events, TrainDeparture)
    ] == [("leader", 200, 0), ("follower", 210, 1)]
    assert [(e.train_id, e.time_s) for e in select(events, Boarding)] == [
        ("follower", 205)
    ]


def test_terminal_alighting_uses_inbound_stop_before_return_trip_advances():
    """A reused vehicle alights at its terminus before its trip index changes.

    A through passenger for the return destination keeps their identity and seat.
    Counts on the return trip must not reuse the inbound terminal alighting.
    """
    metro = vehicle(
        capacity=2,
        onboard_load=2,
        return_trips=(
            (ScheduledStop("B", "R", 300, 320), ScheduledStop("C", "C", 420, 440)),
        ),
    )
    people = {
        "off": person("off", "B", PassengerState.ON_BOARD),
        "through": person("through", "C", PassengerState.ON_BOARD),
    }
    queue, events, _ = simulate(
        [metro], people, initial={"metro": ["off", "through"]}, end_s=500
    )
    assert [
        (e.passenger_id, e.time_s, e.platform_id) for e in select(events, Alighting)
    ] == [("off", 220, "Q"), ("through", 420, "C")]
    assert metro.onboard_load == 0
    assert all(p.state is PassengerState.COMPLETED for p in people.values())
    assert [
        (e.time_s, e.alighted_count, e.onboard_load)
        for e in select(events, TrainDeparture)
    ] == [(120, 0, 2), (320, 0, 1), (440, 1, 0)]


@settings(max_examples=30)
@given(count=st.integers(0, 12), capacity=st.integers(1, 6))
def test_capacity_fifo_and_passenger_conservation(count, capacity):
    """For varying group sizes, every passenger is onboard or still waiting.

    Generated cases vary both demand and seats. Boarding IDs must be the first
    arrivals, and their count plus the platform count must equal input demand.
    """
    people = {f"p{i}": person(f"p{i}") for i in range(count)}
    metro = vehicle(capacity=capacity)
    queue, events, _ = simulate(
        [metro], people, [arrival(key, 10 + i) for i, key in enumerate(people)]
    )
    expected = tuple(people)[:capacity]
    assert [e.passenger_id for e in select(events, Boarding)] == list(expected)
    assert metro.onboard_load == min(count, capacity)
    onboard_count = sum(p.state is PassengerState.ON_BOARD for p in people.values())
    assert onboard_count + queue.waiting_count("P") == count


@pytest.mark.parametrize("transfers_first", [False, True])
def test_transfer_to_destination_timelines_and_filtered_logs_repeat(
    tmp_path, transfers_first
):
    """Real feeder groups finish journeys in either component order.

    Full logs and summaries repeat byte-for-byte; filtering passenger records
    changes output detail without changing identities, final states or loads.
    Feeder transfers count as external alightings, preserving aggregate load.
    """
    finished = []

    def build(_scenario, streams):
        transfers = TransferComponent(
            [
                TransferRoute(
                    "A",
                    "rem",
                    "P",
                    DemandProfile((DemandPeriod(0, 10, 60),)),
                    {"B": 1},
                    CorridorQueue(6000),
                    walking_mean_s=2,
                    walking_min_s=1,
                )
            ],
            streams,
        )
        feeder = Train("feeder", 800, (ScheduledStop("A", "rem", 10, 30),))
        queue = PlatformQueue(("P", "Q"), passengers=transfers.passengers)
        component = TrainComponent(
            [feeder, vehicle(capacity=800, arrival_s=50, departure_s=70)],
            passenger_queue=queue,
        )
        finished.append(queue)
        return [transfers, component] if transfers_first else [component, transfers]

    scenario = SimpleNamespace(master_seed=42, duration_s=400)
    first = run_scenario(scenario, StreamManager, build, tmp_path / "first")
    second = run_scenario(scenario, StreamManager, build, tmp_path / "second")
    filtered = run_scenario(
        scenario,
        StreamManager,
        build,
        tmp_path / "filtered",
        skip_event_types=PASSENGER_EVENT_TYPES,
    )
    assert first.events_path.read_bytes() == second.events_path.read_bytes()
    assert first.summary_path.read_bytes() == second.summary_path.read_bytes()
    assert finished[0].passengers == finished[2].passengers
    assert len(finished[0].passengers) > 0
    assert all(
        p.state is PassengerState.COMPLETED for p in finished[0].passengers.values()
    )
    records = [json.loads(line) for line in first.events_path.read_text().splitlines()]
    for passenger_id in finished[0].passengers:
        assert [
            r["event_type"] for r in records if r.get("passenger_id") == passenger_id
        ] == [
            "alighting",
            "corridor_arrival",
            "passenger_arrival",
            "boarding",
            "alighting",
        ]
    count = len(finished[0].passengers)
    feeder_departure = next(
        r
        for r in records
        if r["event_type"] == "train_departure" and r["train_id"] == "feeder"
    )
    assert (feeder_departure["alighted_count"], feeder_departure["onboard_load"]) == (
        count,
        0,
    )
    assert [
        (r["boarded_count"], r["alighted_count"], r["onboard_load"])
        for r in records
        if r["event_type"] == "train_departure" and r["train_id"] == "metro"
    ] == [(count, 0, count), (0, count, 0)]
    assert all(
        "passenger_id" not in json.loads(line)
        for line in filtered.events_path.read_text().splitlines()
    )
